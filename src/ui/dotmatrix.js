// Renders `text` into `canvas`. `bold` doubles every pixel into a 2x2 block of dots,
// which gives the chunky double-stroke letters of the original countdown.
export function drawDotMatrix(canvas, text, { dot = 10, color = '#39ff5a', glow = '#1aff3a', bold = true } = {}) {
  const k = bold ? 2 : 1;
  const chars = [...text.toUpperCase()].map((ch) => GLYPHS[ch] || GLYPHS[' ']);
  const cols = chars.length * 5 * k + (chars.length - 1) * k;
  const rows = 7 * k;
  const pad = dot * 2;
  const dpr = Math.min(window.devicePixelRatio || 1, 2);
  canvas.width = Math.ceil((cols * dot + pad * 2) * dpr);
  canvas.height = Math.ceil((rows * dot + pad * 2) * dpr);
  canvas.style.width = `${cols * dot + pad * 2}px`;
  canvas.style.height = `${rows * dot + pad * 2}px`;
  const ctx = canvas.getContext('2d');
  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
  ctx.clearRect(0, 0, canvas.width, canvas.height);
  ctx.shadowColor = glow;
  ctx.shadowBlur = dot * 1.4;
  const g = ctx.createRadialGradient(0, 0, 0, 0, 0, dot * 0.45);
  g.addColorStop(0, '#eaffea');
  g.addColorStop(0.45, color);
  g.addColorStop(1, color);
  chars.forEach((glyph, ci) => {
    const ox = ci * 6 * k;
    for (let row = 0; row < 7; row++) {
      for (let col = 0; col < 5; col++) {
        if (glyph[row][col] !== '#') continue;
        for (let by = 0; by < k; by++) {
          for (let bx = 0; bx < k; bx++) {
            const x = pad + (ox + col * k + bx + 0.5) * dot;
            const y = pad + (row * k + by + 0.5) * dot;
            ctx.save();
            ctx.translate(x, y);
            ctx.fillStyle = g;
            ctx.beginPath();
            ctx.arc(0, 0, dot * 0.42, 0, Math.PI * 2);
            ctx.fill();
            ctx.restore();
          }
        }
      }
    }
  });
}
